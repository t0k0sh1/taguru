#!/usr/bin/env python3
"""Generate the JIS X 0208 ideograph bitset (ADR 0039).

Membership comes from Python's `shift_jis` codec (JIS X 0208:1997 +
JIS X 0201): a CJK Unified Ideograph (U+4E00..U+9FFF) that the codec
can encode is in the set. Deterministic — the same table on every run.

    gen_jis_x0208.py                      # Rust: the table in src/extract/jis_x0208.rs
    gen_jis_x0208.py --format python      # sdk/python-langchain/src/taguru_langchain/_jis_x0208.py
    gen_jis_x0208.py --format typescript  # sdk/typescript-langchain/src/jis-x0208.ts

Every producer reads the same 328 words; the SDK test suites check
their copy against src/extract/jis_x0208.rs, so regenerate all three
together rather than editing one.
"""

import argparse

LO, HI = 0x4E00, 0x9FFF


def words() -> tuple[list[int], int]:
    out = []
    count = 0
    for base in range(LO, HI + 1, 64):
        w = 0
        for i in range(64):
            cp = base + i
            if cp > HI:
                break
            try:
                chr(cp).encode("shift_jis")
                w |= 1 << i
                count += 1
            except UnicodeEncodeError:
                pass
        out.append(w)
    return out, count


def rust(table: list[int], count: int) -> str:
    lines = [f"// {count} ideographs, {len(table)} words"]
    lines.append(f"pub(super) const JIS_X0208_IDEOGRAPHS: [u64; {len(table)}] = [")
    for i in range(0, len(table), 4):
        lines.append("    " + ", ".join(f"0x{w:016x}" for w in table[i : i + 4]) + ",")
    lines.append("];")
    return "\n".join(lines)


def python(table: list[int], count: int) -> str:
    lines = [
        '"""JIS X 0208\'s ideograph repertoire (ADR 0039) — the same bitset as',
        "src/extract/jis_x0208.rs. Generated by scripts/gen_jis_x0208.py",
        '--format python; regenerate rather than edit."""',
        "",
        f"# {count} ideographs, {len(table)} words: bit i of word k is U+4E00 + 64k + i.",
        "JIS_X0208_IDEOGRAPHS: tuple[int, ...] = (",
    ]
    for i in range(0, len(table), 4):
        lines.append("    " + ", ".join(f"0x{w:016x}" for w in table[i : i + 4]) + ",")
    lines.append(")")
    return "\n".join(lines)


def typescript(table: list[int], count: int) -> str:
    lines = [
        "/**",
        " * JIS X 0208's ideograph repertoire (ADR 0039) — the same bitset as",
        " * src/extract/jis_x0208.rs, one 16-hex-digit word per 64 code points from",
        " * U+4E00. Generated by scripts/gen_jis_x0208.py --format typescript;",
        " * regenerate rather than edit.",
        " */",
        f"// {count} ideographs, {len(table)} words",
        "export const JIS_X0208_IDEOGRAPHS: readonly string[] = [",
    ]
    for i in range(0, len(table), 4):
        lines.append("  " + ", ".join(f'"{w:016x}"' for w in table[i : i + 4]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--format", choices=("rust", "python", "typescript"), default="rust")
    args = parser.parse_args()
    table, count = words()
    print({"rust": rust, "python": python, "typescript": typescript}[args.format](table, count))


if __name__ == "__main__":
    main()
